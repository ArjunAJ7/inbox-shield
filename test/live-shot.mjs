import puppeteer from 'puppeteer-core';
const browser = await puppeteer.launch({ executablePath: '/usr/bin/google-chrome', headless: 'new', args: ['--no-sandbox','--disable-dev-shm-usage'] });
const page = await browser.newPage();
await page.setViewport({ width: 1100, height: 1100 });
await page.goto('https://inbox-shield.arjun-vinod0028.workers.dev/', { waitUntil: 'domcontentloaded' });
await page.click('#go');
await page.waitForFunction(() => document.querySelector('#out table'), { timeout: 30000 });
await new Promise(r=>setTimeout(r,400));
const el = await page.$('#out');
await el.screenshot({ path: 'test/shot-live-refund.png' });
console.log(await page.evaluate(() => document.querySelector('#out').innerText));
await browser.close();
